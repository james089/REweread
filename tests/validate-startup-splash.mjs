import fs from 'node:fs';
import assert from 'node:assert/strict';
const main=fs.readFileSync('apps/weread-qt/main.cpp','utf8');
const splash=fs.readFileSync('apps/weread-qt/startup_splash.h','utf8');
const session=fs.readFileSync('scripts/weread-qt-session.sh','utf8');
const branch=main.indexOf('return runStartupSplash(app)');
assert(branch>0 && branch<main.indexOf('ShelfStore shelfStore'),'splash must return before account/book stores are constructed');
assert(branch<main.indexOf('engine.loadFromModule'),'splash must bypass the expensive Main.qml load');
assert(splash.includes('正在启动 REweread…'),'startup feedback must identify the app in Chinese');
assert(splash.includes('QQuickWindow::frameSwapped'),'splash must wait for its first rendered frame');
assert(splash.includes('app.exit(2)'),'a missing render must have a bounded timeout');
const launch=session.indexOf('"$APP_BIN" -platform epaper --startup-splash');
const full=session.indexOf('QT_QUICK_BACKEND=epaper RM_WEREAD_QT_SELFTEST="$SELFTEST_MODE"');
assert(launch>session.indexOf('systemctl stop --no-block xochitl'),'splash must respect the system UI handoff');
assert(launch<full,'splash must run before the full application');
assert(session.lastIndexOf('APP_STARTED=1',launch)>session.indexOf('xochitl-state-before-app'),'interrupting the splash must restore the system UI');
assert(session.slice(launch,full).includes('wait "$APP_PID"'),'splash must release its display before the full app starts');
assert(session.slice(0,launch).includes('if [ -z "$SELFTEST_MODE" ]'),'other isolated tests must not start an extra splash');
console.log('startup splash handoff checks ok');
